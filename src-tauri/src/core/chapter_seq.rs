fn concat3(
    a: &'static [&'static str],
    b: &'static [&'static str],
    c: &'static [&'static str],
) -> Vec<&'static str> {
    let mut out = Vec::new();
    out.extend_from_slice(a);
    out.extend_from_slice(b);
    out.extend_from_slice(c);
    out
}

/// 起步构建一次：<subject_key, version_key, 有序条目>
static CHAPTER_SEQ: OnceLock<Vec<(String, String, Vec<&'static str>)>> = OnceLock::new();

fn tables() -> &'static Vec<(String, String, Vec<&'static str>)> {
    CHAPTER_SEQ.get_or_init(|| {
        vec![
            (
                "math".to_string(),
                "数一".to_string(),
                concat3(GAODENG_1, LINDAI, PROB),
            ),
            (
                "math".to_string(),
                "数二".to_string(),
                concat3(GAODENG_2, LINDAI, &[]),
            ),
            (
                "math".to_string(),
                "数三".to_string(),
                concat3(GAODENG_3, LINDAI, PROB),
            ),
            ("politics".to_string(), "".to_string(), POLITICS.to_vec()),
            ("english".to_string(), "".to_string(), ENGLISH.to_vec()),
        ]
    })
}

fn seq_for(subject: &str, version: &str) -> Option<&'static [&'static str]> {
    let v = version.trim();
    for (subj, ver, seq) in tables().iter() {
        if subj != subject {
            continue;
        }
        let maybe = match subj.as_str() {
            "math" => ver == v || v.contains(ver) || ver.contains(v),
            "english" => ver.is_empty() || v.is_empty() || v == "英一" || v == "英二",
            "politics" => true,
            _ => false,
        };
        if maybe {
            return Some(seq);
        }
    }
    None
}

/// 在当前版本顺序表中定位某文本（章节/知识点/任务标题）的位置。
/// 匹配策略：在表中找能在文本中命中的**最长**条目，返回其下标。
/// 未命中返回 None（视为无法确认顺序的内容，不做超前判定）。
pub fn position(subject: &str, version: &str, text: &str) -> Option<usize> {
    let seq = seq_for(subject, version)?;
    let norm = normalize(text);
    let mut best: Option<(usize, usize)> = None;
    for (idx, entry) in seq.iter().enumerate() {
        let ent = normalize(entry);
        if ent.is_empty() {
            continue;
        }
        if norm.contains(&ent) && best.map_or(true, |(_, blen)| ent.len() > blen) {
            best = Some((idx, ent.len()));
        }
        // 文本是单个条目的子串（如进度就填「线性表示」→ 命中「向量组的线性表示」）
        if ent.contains(&norm) && !norm.is_empty() && norm.len() >= 2 {
            best = Some((idx, usize::MAX));
            break;
        }
    }
    best.map(|(i, _)| i)
}

/// 判断某任务标题是否**早于**用户实际进度（即已学过、不应再排）。
pub fn is_ahead_of_progress(
    subject: &str,
    version: &str,
    task_title: &str,
    progress_chapter: &str,
) -> Option<bool> {
    let task_pos = position(subject, version, task_title)?;
    let prog_pos = position(subject, version, progress_chapter)?;
    Some(task_pos <= prog_pos)
}

fn normalize(s: &str) -> String {
    s.chars()
        .filter(|c| !c.is_whitespace())
        .map(|c| {
            if c.is_ascii() {
                c.to_ascii_lowercase()
            } else {
                c
            }
        })
        .collect()
}

